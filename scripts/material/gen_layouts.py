#!/usr/bin/env python3
"""Generate the slide layouts' stylesheet and reference from `core/layouts.py`.

Two outputs from one table, so the browser, the model and the exporter never
disagree about where a slot sits or what it may hold:

- `features/material/theme/layouts.css` — each layout's background and each
  slot's box, as percentages of the slide.
- `references/material/layouts.md` — what the model writes a deck from.

`--check` fails CI when either is stale.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from get_fsa_training_done.features.material.core import i18n  # noqa: E402
from get_fsa_training_done.features.material.core import layouts as L  # noqa: E402

PACKAGE = ROOT / "src" / "get_fsa_training_done"
CSS = PACKAGE / "features" / "material" / "theme" / "layouts.css"
MD = PACKAGE / "payload" / "get-fsa-training-done" / "references" / "material" / "layouts.md"

ANCHOR = {"top": "start", "middle": "center", "bottom": "end"}


def _pct(value: float) -> str:
    return f"{value:g}%"


FAMILY = {
    L.DISPLAY: "var(--font-display)",
    L.SANS: "var(--font-sans)",
    L.MINOR: "var(--font-minor)",
}


def _box(box: L.Box) -> str:
    return (
        f"left: {_pct(box.left)}; top: {_pct(box.top)}; "
        f"width: {_pct(box.width)}; height: {_pct(box.height)}"
    )


def _text(slot: L.Slot) -> str:
    rules = [
        f"--slot-size: {slot.size}pt",
        f"color: #{slot.colour}",
        f"font-family: {FAMILY[slot.font]}",
        f"align-content: {ANCHOR[slot.anchor]}",
        f"font-weight: {700 if slot.bold else 400}",
    ]
    if slot.italic:
        rules.append("font-style: italic")
    if slot.fits:
        rules.append("--slot-fit: 1")
    if slot.align != "left":
        rules.append(f"text-align: {slot.align}")
    return "; ".join(rules)


def _rules(selector: str, layout: L.Layout) -> str:
    """The layout's ruled lines as background layers over its image."""
    ink = f"linear-gradient(#{L.RULE_COLOUR}, #{L.RULE_COLOUR})"
    images, sizes, positions = [], [], []
    for rule in layout.rules:
        width = f"{L.RULE_WIDTH_PT:g}pt" if rule.width == 0 else f"{rule.width_pt:.2f}pt"
        height = f"{L.RULE_WIDTH_PT:g}pt" if rule.height == 0 else f"{rule.height_pt:.2f}pt"
        images.append(ink)
        sizes.append(f"{width} {height}")
        positions.append(
            f"{rule.left / 100 * L.SLIDE_WIDTH_PT:.2f}pt {rule.top / 100 * L.SLIDE_HEIGHT_PT:.2f}pt"
        )
    images.append(f"url(img/{layout.background}.jpg)")
    sizes.append("100% 100%")
    positions.append("0 0")
    return (
        f"{selector} {{ background-image: {', '.join(images)}; "
        f"background-size: {', '.join(sizes)}; background-position: {', '.join(positions)}; }}"
    )


def render_css() -> str:
    lines = [
        "/* Generated by scripts/material/gen_layouts.py from",
        "   src/get_fsa_training_done/features/material/core/layouts.py.",
        "   Do not edit by hand; edit the Python and regenerate. */",
        "",
        "/* The fit estimate deck.js shares with the exporters (layouts.fit_scale). */",
        ":root {",
        f"  --fit-scales: {' '.join(f'{scale:g}' for scale in L.FIT_SCALES)};",
        f"  --fit-char-em: {L.CHAR_EM[False]:g};",
        f"  --fit-char-em-bold: {L.CHAR_EM[True]:g};",
        f"  --fit-space-em: {L.SPACE_EM:g};",
        f"  --slot-line-height: {L.LINE_HEIGHT:g};",
        f"  --slot-inset-x: {L.INSET_X:g}pt;",
        f"  --slot-inset-y: {L.INSET_Y:g}pt;",
        "}",
        "",
    ]
    for layout in L.LAYOUTS:
        selector = f'.slide[data-layout="{layout.name}"]'
        # Prefixed so the theme's generic `.fsa-deck .slide` background rules,
        # which come after this file, do not override a layout's own.
        backdrop = f".fsa-deck {selector}"
        lines.append(f"{backdrop} {{ background-image: url(img/{layout.background}.jpg); }}")
        if layout.rules:
            lines.append(_rules(backdrop, layout))
        if layout.background_box is not None:
            box = layout.background_box
            lines.append(
                f"{backdrop} {{ background-size: {_pct(box.width)} {_pct(box.height)}; "
                f"background-position: 100% 0; }}"
            )
        for slot in layout.slots:
            target = f'{selector} > [data-slot="{slot.name}"]'
            lines.append(f"{target} {{ {_box(slot.box)}; {_text(slot)}; }}")
            if slot.default:
                lines.append(
                    f'{selector}:not(:has(> [data-slot="{slot.name}"]))::before '
                    f"{{ {_box(slot.box)}; {_text(slot)}; }}"
                )
        lines.append("")

    footed = [
        f'.slide[data-layout="{layout.name}"]::after' for layout in L.LAYOUTS if layout.footer
    ]
    lines.append("/* The copyright line and slide number of every layout that carries them. */")
    lines.append(",\n".join(footed) + " { display: block; }")
    lines.append("")

    lines.append("/* The table of contents: a numbered circle and a title per row. */")
    for row, ((_, number), (_, title)) in enumerate(L.TOC_ROWS, 1):
        lines.append(f".slide .toc-rows > li:nth-child({row}) > .toc-num {{ {_box(number)}; }}")
        lines.append(f".slide .toc-rows > li:nth-child({row}) > .toc-title {{ {_box(title)}; }}")
    lines.append(f".slide .toc-rows > li > * {{ font-size: {L.TOC_SIZE}pt; }}")
    lines.append("")
    lines.extend(_labels())
    return "\n".join(lines) + "\n"


def _css_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


#: Theme labels: the element they decorate, and the words before it.
LABELS = (
    (".slide .wrong{lang}::before", "\\2717  ", "Wrong"),
    (".slide .right{lang}::before", "\\2713  ", "Right"),
    (".fsa-doc pre.wrong{lang}::before", "\\2717  ", "Wrong"),
    (".fsa-doc pre.right{lang}::before", "\\2713  ", "Right"),
    (".fsa-doc .try-it{lang}::before", "", "Try it"),
    (".fsa-doc p.expected{lang}::before", "", "You should see:"),
)


#: Words the scripts write (deck.js, doc.js), exposed as custom properties
#: they read back, so the strings live only in core/i18n.py.
SCRIPT_WORDS = {
    "--t-session": "Session",
    "--t-min": "min",
    "--t-hint": "N notes · O overview",
    "--t-no-notes": "No speaker notes for this slide.",
}


def _labels() -> list[str]:
    """The theme's words and the slides' default titles, per language (core/i18n.py)."""
    lines = ["/* Labels in the page's language, from core/i18n.py. */"]
    for lang in i18n.languages():
        scope = "" if lang == i18n.DEFAULT else f":lang({lang})"
        words = "; ".join(
            f"{name}: {_css_string(i18n.t(lang, text))}" for name, text in SCRIPT_WORDS.items()
        )
        lines.append(f":root{scope} {{ {words}; }}")
        for selector, prefix, text in LABELS:
            words = i18n.t(lang, text) + (" " if text.endswith(":") else "")
            content = (f'"{prefix}" ' if prefix else "") + _css_string(words)
            lines.append(f"{selector.format(lang=scope)} {{ content: {content}; }}")
        for layout in L.LAYOUTS:
            for slot in layout.slots:
                if slot.default:
                    lines.append(
                        f'.slide[data-layout="{layout.name}"]{scope}'
                        f':not(:has(> [data-slot="{slot.name}"]))::before '
                        f"{{ content: {_css_string(i18n.t(lang, slot.default))}; }}"
                    )
    return lines


def render_md() -> str:
    lines = [
        "# Slide layouts",
        "",
        "The layouts a deck may use. Each is a layout of the FSA training-materials",
        "template, and each slot is one of its placeholders, so a deck written to",
        "this page looks the same in the browser and in the exported `.pptx`.",
        "",
        "```html",
        '<section class="slide" data-layout="content">',
        '  <h2 data-slot="title">Joins keep matching rows</h2>',
        '  <div data-slot="body">',
        "    <ul><li>An inner join keeps rows that match on both sides</li></ul>",
        "  </div>",
        '  <aside class="notes">What the trainer says over this slide.</aside>',
        "</section>",
        "```",
        "",
        "- `title` and `text` slots hold inline text only. Text that does not fit",
        "  shrinks in steps, down to "
        + f"{min(L.FIT_SCALES):.0%}"
        + " of the template's size; past that `verify` warns (`MAT-S08`).",
        "- `body` slots hold paragraphs, lists (two levels), one code block, a table,",
        '  or a `<figure>`. A check slide adds `data-role="check"` and puts the',
        "  answer in `<details>`.",
        "- `picture` slots hold one `<img>`.",
        f"- Code on a slide: at most {L.MAX_CODE_LINES} lines.",
        f"- Speaker notes: at least {L.MIN_NOTE_WORDS} words on every objectives and",
        "  content slide.",
        "- A slot marked *default* may be left out; the template's own wording is used.",
        "",
        "<!-- Generated by scripts/material/gen_layouts.py from",
        "     src/get_fsa_training_done/features/material/core/layouts.py.",
        "     Do not edit by hand; edit the Python and regenerate. -->",
        "",
        "## Order",
        "",
        "`cover` → `toc` (optional) → `objectives` → for each section: `section`,",
        "then its content slides, at least one of them a check → `summary` →",
        "`closing` or `closing-alt`.",
        "",
        "## Layouts",
        "",
        "| `data-layout` | Template layout | Role | Use it for |",
        "|---|---|---|---|",
    ]
    for layout in L.LAYOUTS:
        lines.append(f"| `{layout.name}` | {layout.pptx_name} | {layout.role} | {layout.summary} |")
    for layout in L.LAYOUTS:
        lines += ["", f"### `{layout.name}`", "", layout.summary, ""]
        if not layout.slots:
            continue
        lines.append("| `data-slot` | Holds | Required | Limit | Size |")
        lines.append("|---|---|---|---|---|")
        for slot in layout.slots:
            required = (
                "yes" if slot.required else (f"default: {slot.default}" if slot.default else "no")
            )
            limit = (
                f"{slot.max_items} items"
                if slot.max_items
                else ("shrinks to fit" if slot.fits else "—")
            )
            size = f"{slot.size} pt" if slot.size else "—"
            lines.append(f"| `{slot.name}` | {slot.kind} | {required} | {limit} | {size} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if an output is stale")
    args = parser.parse_args()

    stale = []
    for target, content in ((CSS, render_css()), (MD, render_md())):
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if args.check:
            if current != content:
                stale.append(target)
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
        print(f"wrote {target.relative_to(ROOT)}")

    if args.check:
        for target in stale:
            print(f"ERROR: {target.relative_to(ROOT)} is out of date", file=sys.stderr)
        if stale:
            print("run `python scripts/material/gen_layouts.py` to regenerate", file=sys.stderr)
            return 1
        print("layouts.css and layouts.md are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
