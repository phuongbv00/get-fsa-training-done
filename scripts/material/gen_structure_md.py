#!/usr/bin/env python3
"""Generate the material skill's `references/structure.md` from `core/grammar.py`.

The model writes documents from this file; `verify` checks them against the
Python. Prose describing a required section the checker does not enforce would
calibrate the model to a constraint nothing holds it to — and prose omitting one
it does enforce produces documents that fail a check the docs never mentioned.
So the templates and the rulebook are both generated, and `--check` fails CI
when either is stale.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from get_fsa_training_done.features.material.core import grammar as G  # noqa: E402
from get_fsa_training_done.features.material.core import rules as R  # noqa: E402

TARGET = (
    ROOT
    / "src"
    / "get_fsa_training_done"
    / "payload"
    / "get-fsa-training-done"
    / "references"
    / "material"
    / "structure.md"
)

HEADER = """# Document structure

What each kind of teaching material is shaped like, and every rule
`FSA material verify` applies. Both come from the same definitions the checker
executes, so nothing here is a constraint the tool does not enforce.

Material is **HTML on the FSA theme**: one file per artifact, the source of
truth, from which `FSA material export` derives the `.pptx` and `.pdf`. In order
of how much a trainee learns from them: the slide deck, the handbook, the
lecture note, then the lab guide. The slide layouts are in
`references/material/layouts.md`.

Universal, whatever the kind:

- `<meta charset="utf-8">`, a `<title>`, and `<meta name="fsa:kind">` naming the
  kind the filename claims, plus the kind's other required `fsa:` metas.
- `<link rel="stylesheet" href="_theme/fsa.css">` and **no styling of the page's
  own**: no `style` attribute, no `<style>`, no `<font>`. Run
  `FSA material init --dir <folder>` once to put the theme there.
- Every code block is `<pre><code class="language-…">`; a diagram is
  `<figure><pre class="mermaid">…</pre></figure>`, with an `<img>` of it beside
  the source when the document will be exported.
- Relative links and images resolve, and so do `#ids`.
- English, unless the filename ends `_vn` to mark a translation.

<!-- Generated by scripts/material/gen_structure_md.py from
     src/get_fsa_training_done/features/material/core/{grammar,rules}.py.
     Do not edit by hand; edit the Python and regenerate. -->
"""


def render() -> str:
    lines = [HEADER, "\n## Naming\n"]
    lines.append("| Kind | Filename |")
    lines.append("|---|---|")
    for kind in sorted(G.KINDS, key=lambda k: k.rank):
        lines.append(f"| {kind.title} | `{kind.filename.pattern}` |")
    lines.append("")
    lines.append(
        f"Index `{G.HANDBOOK_INDEX}` is the handbook and `{G.APPENDIX_INDEX}` the appendix. "
        "A lesson's deck carries its index: `01_Relational_Modelling.deck.html`. A "
        "trailing letter marks an aside outside the syllabus (`02b_...`). The lecture "
        "note is one file per module, named for its subject like the labs: "
        f"`dbf_lecture_note.html`. `{G.TRANSLATION_SUFFIX}` before the extension marks "
        "a translation.\n"
    )

    for kind in sorted(G.KINDS, key=lambda k: k.rank):
        lines.append(f"\n## {kind.title}\n")
        lines.append(f"{kind.summary}\n")
        lines.append(f'`<body class="{kind.body_class}">`. Required metas: ')
        lines[-1] += ", ".join(f"`{name}`" for name in kind.required_meta) + ".\n"
        if kind.parts:
            lines.append(
                'Each part is a `<section data-part="…" id="…">` opening with an `<h2>`, '
                "in this order. The theme numbers the headings.\n"
            )
            lines.append("| `data-part` | Heading | Required | Holds |")
            lines.append("|---|---|---|---|")
            for part in kind.parts:
                required = "yes" if part.required else "optional"
                if part.repeatable:
                    required += ", repeated"
                lines.append(f"| `{part.key}` | {part.heading} | {required} | {part.description} |")
            lines.append("")

    lines.append("\n## Code languages\n")
    lines.append(
        "Anything outside this set is reported as a warning rather than an "
        "error — a module may legitimately introduce a language.\n"
    )
    lines.append(", ".join(f"`{name}`" for name in G.CODE_LANGUAGES) + "\n")

    for scope, title, blurb in (
        ("document", "Rules — one document", "Applied to every file `verify` reads."),
        ("deck", "Rules — a slide deck", "Applied to a deck, against the FSA template."),
        (
            "export",
            "Rules — exporting",
            "Applied by `export`, and by `verify --export`: what a .pptx or .pdf cannot carry.",
        ),
        (
            "coverage",
            "Rules — material against the session plan",
            "Applied by `coverage`, comparing a folder with the plan that asks for it.",
        ),
    ):
        in_scope = [rule for rule in R.RULES if rule.scope == scope]
        lines.append(f"\n## {title}\n")
        lines.append(f"{blurb}\n")
        lines.append("| Rule | Severity | Checks |")
        lines.append("|---|---|---|")
        for rule in in_scope:
            lines.append(f"| `{rule.id}` | {rule.severity} | {rule.title} |")
        lines.append("")
        for rule in in_scope:
            lines.append(f"### `{rule.id}` — {rule.title}\n")
            lines.append(f"{rule.rationale}\n")

    counts = {
        severity: sum(1 for rule in R.RULES if rule.severity == severity)
        for severity in ("error", "warning")
    }
    lines.append(
        f"---\n\n{len(R.RULES)} rules: {counts['error']} errors, {counts['warning']} warnings.\n"
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the file is stale")
    args = parser.parse_args()

    content = render()
    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""

    if args.check:
        if current != content:
            print(f"ERROR: {TARGET.relative_to(ROOT)} is out of date", file=sys.stderr)
            print(
                "run `python scripts/material/gen_structure_md.py` to regenerate", file=sys.stderr
            )
            return 1
        print("structure.md is up to date")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(G.KINDS)} kinds, {len(R.RULES)} rules)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
